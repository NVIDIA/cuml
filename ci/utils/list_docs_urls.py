"""List the pages of the published cuML docs for the weekly link check.

Writes two files used as lychee inputs:

- a list of page URLs, read from the published ``objects.inv``, which lychee
  downloads to check every link on each page
- a Markdown file linking each redirect page from ``REDIRECTS`` in
  ``docs/source/conf.py`` and its target. lychee doesn't follow
  ``<meta http-equiv="refresh">``, so a redirect to a removed page would
  otherwise go unnoticed.

Only the standard library is used, so this runs on a plain GitHub runner.
"""

import argparse
import ast
import re
import urllib.request
import zlib
from pathlib import Path

DEFAULT_BASE_URL = "https://docs.nvidia.com/cuml/latest/"

# One entry of a Sphinx v2 inventory: name, domain:role, priority, uri, display
# name. Same pattern as sphinx.util.inventory; the lazy `\s+?` keeps an empty
# uri (the root page) from swallowing the display name.
INVENTORY_ENTRY = re.compile(r"(.+?)\s+(\S+)\s+(-?\d+)\s+?(\S*)\s+(.*)")


def list_pages(base_url):
    """Return the URL of every document listed in the published objects.inv."""
    with urllib.request.urlopen(base_url + "objects.inv") as f:
        data = f.read()

    # Four plain-text header lines, then the zlib-compressed entries
    header_lines = data.split(b"\n", 4)
    if not header_lines[0].startswith(b"# Sphinx inventory version 2"):
        raise ValueError(f"Unsupported inventory format: {header_lines[0]!r}")
    body = zlib.decompress(header_lines[4]).decode("utf-8")

    pages = []
    for line in body.splitlines():
        match = INVENTORY_ENTRY.match(line.rstrip())
        if match is None:
            continue
        name, domain_role, _priority, uri, _display = match.groups()
        if domain_role != "std:doc":
            continue
        if uri.endswith("$"):
            uri = uri[:-1] + name
        pages.append(base_url + uri)
    return sorted(set(pages))


def read_redirects(conf_path):
    """Return the REDIRECTS mapping from conf.py without importing it."""
    tree = ast.parse(Path(conf_path).read_text())
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "REDIRECTS"
        ):
            return ast.literal_eval(node.value)
    raise ValueError(f"REDIRECTS not found in {conf_path}")


def redirects_markdown(base_url, redirects):
    """Return Markdown linking each redirect page and the page it points to."""
    lines = [
        "# Redirects in the published docs",
        "",
        "Generated by `ci/utils/list_docs_urls.py` from `REDIRECTS` in `docs/source/conf.py`.",
        "",
    ]
    for old_path, new_path in sorted(redirects.items()):
        old_url = base_url + old_path.removesuffix("index.html")
        new_url = base_url + new_path
        lines.append(f"- <{old_url}> redirects to <{new_url}>")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL)
    parser.add_argument(
        "--conf",
        default="docs/source/conf.py",
        help="Sphinx conf.py that defines REDIRECTS",
    )
    parser.add_argument(
        "--pages",
        required=True,
        help="Output file for the page URLs, one per line",
    )
    parser.add_argument(
        "--redirects",
        required=True,
        help="Output Markdown file linking each redirect and its target",
    )
    args = parser.parse_args()

    base_url = args.base_url.rstrip("/") + "/"
    pages = list_pages(base_url)
    redirects = read_redirects(args.conf)

    for path in (args.pages, args.redirects):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(args.pages).write_text("\n".join(pages) + "\n")
    Path(args.redirects).write_text(redirects_markdown(base_url, redirects))

    print(f"Wrote {len(pages)} page URLs to {args.pages}")
    print(f"Wrote {len(redirects)} redirects to {args.redirects}")


if __name__ == "__main__":
    main()
